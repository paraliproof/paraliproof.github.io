// profile.js — signed DEMO STATE PROFILES (trust-model D8, Phase 4a, 29 Oct). NO DOM CODE HERE.
//
// A state profile is DATA, not code: state id and name, incentive rate (or none), eligible methods, the
// officer role table (level ids → names in en/hi/pa → powers → tabs), audit rates, machine capacity
// limits, languages (first = default), the HQ export column map and the authority public keys for
// stickers and slips. It is signed by that state's DEMO root key; the app pins the root public keys
// (js/stateroots.js) and refuses a profile that is unsigned, changed after signing, signed by another
// key, malformed, or OLDER than a version this phone has already accepted (no rollback).
// The core (recording, signing, verifying, payable = min of three, "never auto-pay / auto-reject") is the
// same in every state; switching the profile only changes names, money display, rules and export format.
//
// Signed form: { schema: 'paraliproof.state-profile.v1', profile: {…}, sig } with sig = ECDSA P-256 over
// canonical(profile). Generated by app/tools/make_demo_state.mjs (private keys in deliverables/demo-qr/).

import { canonical } from './util.js';
import { verifyText, isValidPubB64u } from './crypto.js';
import { STATE_ROOTS } from './stateroots.js';
import { LEVEL_IDS, setRoleTable } from './govroles.js';

export const PROFILE_SCHEMA = 'paraliproof.state-profile.v1';
const IMPL = ['HS', 'SS', 'BL', 'MU', 'OT'];
const POWERS = ['scan', 'visit', 'decide', 'enrol', 'countersign', 'audit', 'seed', 'dashboard', 'batch', 'dlec', 'demo'];
const TABS = ['verify', 'dash', 'phones', 'queue', 'audit', 'visits', 'log', 'approvals', 'district', 'batch', 'dlec', 'state'];
const HQ_COLS = ['format', 'cert_id', 'cert_sha256', 'slip_hash', 'machine_hash', 'stage', 'flags', 'payable_acres', 'registered_acres', 'rate_inr_per_acre', 'indicative_inr', 'job_date', 'dlec_batch', 'demo', 'parcel_hash', 'slip_source'];
const txt = (s, n = 160) => typeof s === 'string' && s.length > 0 && s.length <= n && !/[<>`\u0000-\u001f\u007f]/.test(s);
const names = (o, n = 80) => o && typeof o === 'object' && txt(o.en, n) && ['hi', 'pa'].every((l) => o[l] === undefined || txt(o[l], n)) && Object.keys(o).every((k) => ['en', 'hi', 'pa'].includes(k));
const num = (x, a, b) => typeof x === 'number' && Number.isFinite(x) && x >= a && x <= b;

/** Schema check of the profile body. @returns {string|null} reason when NOT acceptable. */
export function checkProfile(p) {
  if (!p || typeof p !== 'object' || Array.isArray(p)) return 'profile is not an object';
  const known = ['v', 'id', 'version', 'state', 'name', 'demo', 'scheme', 'rate', 'currency', 'methods', 'roleTable', 'audit', 'capacity', 'langs', 'export', 'keys', 'notes', 'issued'];
  for (const k of Object.keys(p)) if (!known.includes(k)) return `unknown field "${String(k).slice(0, 12)}"`;
  if (p.v !== 1) return 'unsupported profile version';
  if (typeof p.id !== 'string' || !/^DEMO-[A-Z]{2}$|^[A-Z]{2}$/.test(p.id)) return 'bad profile id';
  if (typeof p.version !== 'string' || !/^\d{4}\.\d{1,3}$/.test(p.version)) return 'bad profile version (YYYY.N)';
  if (typeof p.state !== 'string' || !/^[A-Z]{2}$/.test(p.state)) return 'bad state code';
  if (!names(p.name)) return 'bad state name';
  if (p.demo !== undefined && p.demo !== 1) return 'bad demo marker';
  if (!names(p.scheme, 200)) return 'bad scheme text';
  if (!(p.rate === null || num(p.rate, 0, 100000))) return 'rate must be a number or null (no cash scheme)';
  if (!Array.isArray(p.methods) || !p.methods.length || !p.methods.every((m) => IMPL.includes(m))) return 'bad eligible methods';
  const rt = p.roleTable;
  if (!rt || typeof rt.id !== 'string' || !Array.isArray(rt.levels) || rt.levels.length < 1 || rt.levels.length > 6) return 'bad role table';
  for (const l of rt.levels) {
    if (!LEVEL_IDS.includes(l?.id) || !names(l.name) || (l.duty !== undefined && !names(l.duty, 200))) return 'bad role level';
    if (!Array.isArray(l.powers) || !l.powers.every((x) => POWERS.includes(x)) || !Array.isArray(l.tabs) || !l.tabs.length || !l.tabs.every((x) => TABS.includes(x))) return 'bad role powers or tabs';
  }
  if (new Set(rt.levels.map((l) => l.id)).size !== rt.levels.length) return 'duplicate role level';
  if (!p.audit || !num(p.audit.rate, 0, 1) || !num(p.audit.selfRate, 0, 1)) return 'bad audit rates';
  if (!p.capacity || !IMPL.every((m) => p.capacity[m] === undefined || num(p.capacity[m], 1, 200))) return 'bad capacity limits';
  if (!Array.isArray(p.langs) || !p.langs.length || !p.langs.every((l) => ['en', 'hi', 'pa'].includes(l))) return 'bad languages';
  if (!p.export || !txt(p.export.format, 40) || !Array.isArray(p.export.columns) || !p.export.columns.every((c) => Array.isArray(c) && c.length === 2 && HQ_COLS.includes(c[0]) && txt(c[1], 40))) return 'bad export column map';
  if (!p.keys || !isValidPubB64u(p.keys.sticker) || !isValidPubB64u(p.keys.slip)) return 'bad authority keys';
  if (!Array.isArray(p.notes) || !p.notes.every((n) => txt(n, 300))) return 'bad notes';
  return null;
}

const verNum = (v) => { const [y, n] = String(v).split('.').map(Number); return y * 1000 + n; };
/**
 * Verify a signed profile against the pinned roots.
 * @param {object} signed  { schema, profile, sig }
 * @param {object} [opts]  roots (id → public key), seen (id → highest version accepted on this phone)
 * @returns {Promise<{ok:boolean, reason?:string, profile?:object, rootPub?:string}>}
 */
export async function verifyProfile(signed, { roots = STATE_ROOTS, seen = {} } = {}) {
  if (!signed || typeof signed !== 'object' || signed.schema !== PROFILE_SCHEMA) return { ok: false, reason: 'Not a ParaliProof state profile' };
  const bad = checkProfile(signed.profile);
  if (bad) return { ok: false, reason: 'Profile refused: ' + bad };
  const p = signed.profile;
  if (typeof signed.sig !== 'string' || !signed.sig) return { ok: false, reason: `Profile ${p.id} refused: it is not signed` };
  const root = roots[p.id];
  if (!root) return { ok: false, reason: `Profile ${p.id} refused: no pinned root key for this state` };
  let sigOk = false;
  try { sigOk = await verifyText(root.pub, canonical(p), signed.sig); } catch { sigOk = false; }
  if (!sigOk) return { ok: false, reason: `Profile ${p.id} refused: the signature does not match the state key (changed after signing, or signed by someone else)` };
  if (seen[p.id] && verNum(p.version) < verNum(seen[p.id])) return { ok: false, reason: `Profile ${p.id} ${p.version} refused: this phone already accepted the newer version ${seen[p.id]}` };
  return { ok: true, profile: p, rootPub: root.pub, rootName: root.name };
}

// ---------------- active profile ----------------
let active = null;
export const activeProfile = () => active;
/** Load and verify the shipped profiles; returns [{ok, profile|reason}] (refused ones included, with the reason). */
export async function shippedProfiles(seen = {}) {
  const { default: list } = await import('../profiles/state-profiles.js');
  return Promise.all(list.map((s) => verifyProfile(s, { seen })));
}
/**
 * Make profile `id` active (or none with id = null). Applies names, rate, rules and export format to
 * `settings` (the caller saves them). Throws with a clear message when the profile is refused.
 * `switched` = the user picked it now (then the profile's first language becomes the app language).
 */
export async function activate(settings, id, { kv, switched = false } = {}) {
  if (!id) { active = null; settings.stateProfile = null; setRoleTable(null); return null; }
  const seen = (kv && (await kv.get('profileSeen'))) || {};
  const all = await shippedProfiles(seen);
  const hit = all.find((r) => r.profile?.id === id) || all.find((r) => !r.ok && r.reason?.includes(id));
  if (!hit) throw new Error(`No state profile ${id} on this phone`);
  if (!hit.ok) throw new Error(hit.reason);
  const p = hit.profile;
  active = { ...p, rootName: hit.rootName };
  setRoleTable(p.roleTable);
  if (kv && (!seen[p.id] || verNum(p.version) > verNum(seen[p.id]))) await kv.set('profileSeen', { ...seen, [p.id]: p.version });
  settings.stateProfile = p.id;
  settings.rate = p.rate ?? 0;
  settings.auditRate = p.audit.rate; settings.auditRateSelf = p.audit.selfRate;
  settings.capacity = { ...settings.capacity, ...p.capacity };
  if (switched) settings.lang = p.langs[0];
  return active;
}
/** "DEMO-HR@2026.1" — signed into new certificates as sp (which rules applied). */
export const profileTag = () => (active ? `${active.id}@${active.version}` : null);
export const noCashScheme = () => !!active && active.rate === null;
